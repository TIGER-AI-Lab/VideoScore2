temp = Template("""
You are an expert for evaluating and thinking about the quality of AI videos from diverse dimensions.

We would like to evaluate its quality from three dimensions: 'visual quality', 'text-to-video alignment' and 'physical consistency'. Below is the definition of each dimension: 
(1) visual quality: 
The dimension 'visual quality' cares about the video's visual and optical propertities, including 'resolution, overall clarity, local blurriness, smoothness, stability of brightness/contrast, distortion/misalignment, abrupt changes, and any other factors the affect the watching experience'. The keywords written by the annotators are also mostly derived from the above factors.
(2) text-to-video alignment:
The dimension 't2v_alignment' mainly assesses whether the generated video fully and accurately depicts the elements mentioned in the text prompt, such as characters, actions, animals, etc., as well as background, quantity, color, weather, and so on. So the keywords written by annotators sometimes only indicate the elements that are missing from the video.
(3) physical/common-sense consistency:
The dimension 'physical/common-sense consistency' mainly examines whether there are any violations of common sense, physical laws, or any other aspects in the video that appear strange or unnatural. Most of the keywords provided by annotators point out the specific abnormalities or inconsistencies they observed in the video.

Here we provide an AI video generated by text-to-video models and its text prompt: 
$t2v_prompt.

Based on the video content and the dimension definitions, please evaluate the video quality and give the quality score. 
The quality score must be integars in the range of 1 - 5.

Your output must be in the following format:
visual quality: <v_score>; 
text-to-video alignment: <t_score>,
physical/common-sense consistency: <p_score>

DO NOT include any other things behind or after your output.
""")

video_path = "/data/xuan/workdir/VideoScore2/other/example_high_res_videos/000000_r.mp4"
