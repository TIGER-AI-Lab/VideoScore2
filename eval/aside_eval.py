def plot_hist(data,path,interval=50):
    import matplotlib.pyplot as plt
    import numpy as np
    data = np.array(data)
    min_val = data.min()
    max_val = data.max()

    bins = np.arange(min_val-interval, max_val + interval, interval)

    plt.hist(data, bins=bins, edgecolor='black')
    plt.xlabel("Value")
    plt.ylabel("Count")
    plt.title("Histogram (interval = 50)")
    plt.grid(axis='y', linestyle='--', alpha=0.7)
    plt.savefig(path)

